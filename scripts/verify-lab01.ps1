#requires -Version 7.0
<#
.SYNOPSIS
Replays laboratory 1 API requests against an already running service.
.DESCRIPTION
Part1 checks the starter API. Part2 creates a separate three-task statistics fixture.
IncludePastDueValidation checks the optional rule only after it is implemented.
Each invocation writes actual requests, responses, safe headers and assertions to a
new evidence/lab01 run directory, including when a request fails. No evidence is
generated by importing the Postman collection or merely inspecting this script.
Only projects created by this invocation are removed, unless KeepData is selected.
The script never starts, stops or restarts the application.
.EXAMPLE
pwsh -File scripts/verify-lab01.ps1 -Phase Part1 -KeepData
.EXAMPLE
pwsh -File scripts/verify-lab01.ps1 -Phase Part2
.EXAMPLE
pwsh -File scripts/verify-lab01.ps1 -Phase All -IncludePastDueValidation
#>
[CmdletBinding()]
param(
    [ValidateSet('Part1', 'Part2', 'All')]
    [string] $Phase = 'All',

    [string] $BaseUrl = 'http://localhost:8088',

    [string] $EvidenceDirectory = (Join-Path (Split-Path $PSScriptRoot -Parent) 'evidence/lab01'),

    [switch] $IncludePastDueValidation,

    [switch] $KeepData
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$baseAddress = $null
if (-not [Uri]::TryCreate($BaseUrl, [UriKind]::Absolute, [ref] $baseAddress) -or
    $baseAddress.Scheme -notin @('http', 'https') -or $baseAddress.UserInfo -or
    $baseAddress.Query -or $baseAddress.Fragment) {
    throw 'BaseUrl must be an absolute HTTP(S) URL without credentials, a query or a fragment.'
}
$BaseUrl = $BaseUrl.TrimEnd('/')
$runId = '{0}-{1}-{2}' -f [DateTime]::UtcNow.ToString('yyyyMMddTHHmmssfffZ'), $Phase.ToLowerInvariant(), [Guid]::NewGuid().ToString('N').Substring(0, 8)
$runDirectory = Join-Path $EvidenceDirectory $runId
$null = New-Item -ItemType Directory -Path $runDirectory -Force
$exchanges = [Collections.Generic.List[object]]::new()
$createdProjectIds = [Collections.Generic.List[int]]::new()
$startedAt = [DateTimeOffset]::UtcNow
$failure = $null
$cleanupFailures = [Collections.Generic.List[string]]::new()
$missingId = [int]::MaxValue

function Assert-Response {
    param(
        [System.Collections.IDictionary] $Exchange,
        [string] $Name,
        [bool] $Condition,
        [string] $Details
    )

    $Exchange.Assertions.Add([ordered]@{ name = $Name; passed = $Condition; details = $Details })
    if (-not $Condition) {
        throw "Request '$($Exchange.Name)': $Name. $Details"
    }
}

function Invoke-Api {
    param(
        [string] $Name,
        [string] $Method,
        [string] $Path,
        [int] $ExpectedStatus,
        [object] $Body = $null
    )

    $requestHeaders = @{ Accept = 'application/json' }
    $requestOptions = @{
        Uri = "$BaseUrl$Path"
        Method = $Method
        Headers = $requestHeaders
        SkipHttpErrorCheck = $true
        MaximumRedirection = 0
        TimeoutSec = 30
    }
    if ($null -ne $Body) {
        $requestOptions.ContentType = 'application/json; charset=utf-8'
        $requestOptions.Body = $Body | ConvertTo-Json -Depth 10 -Compress
        $requestHeaders['Content-Type'] = $requestOptions.ContentType
    }

    $exchange = [ordered]@{
        sequence = $exchanges.Count + 1
        name = $Name
        timestampUtc = [DateTimeOffset]::UtcNow.ToString('O')
        request = [ordered]@{ method = $Method; url = $requestOptions.Uri; headers = $requestHeaders; body = $Body }
        expectedStatus = $ExpectedStatus
        response = $null
        transportError = $null
        assertions = [Collections.Generic.List[object]]::new()
    }
    $exchanges.Add($exchange)
    $timer = [Diagnostics.Stopwatch]::StartNew()
    try {
        $response = Invoke-WebRequest @requestOptions
    }
    catch {
        $exchange.TransportError = $_.Exception.Message
        throw
    }
    finally {
        $timer.Stop()
        $exchange['durationMs'] = $timer.ElapsedMilliseconds
    }

    # Keep diagnostic headers without recording cookies or authentication material.
    $safeHeaders = [ordered]@{}
    foreach ($headerName in @('Content-Type', 'Content-Length', 'Location', 'Date', 'Server', 'Traceparent', 'X-Correlation-ID')) {
        if ($response.Headers.ContainsKey($headerName)) {
            $safeHeaders[$headerName] = $response.Headers[$headerName] -join ', '
        }
    }
    $rawBody = [string] $response.Content
    $parsedBody = $null
    if (-not [string]::IsNullOrWhiteSpace($rawBody)) {
        try { $parsedBody = ConvertFrom-Json -InputObject $rawBody -AsHashtable -Depth 30 -NoEnumerate }
        catch { $parsedBody = $rawBody }
    }
    $exchange.Response = [ordered]@{
        statusCode = [int] $response.StatusCode
        reason = $response.StatusDescription
        headers = $safeHeaders
        body = $parsedBody
        bodyText = $rawBody
    }
    Assert-Response $exchange 'HTTP status' ($response.StatusCode -eq $ExpectedStatus) "Expected $ExpectedStatus, received $($response.StatusCode)."
    return $exchange
}

function New-LabProject {
    param([string] $Suffix)
    $name = "lab01-$runId-$Suffix"
    $exchange = Invoke-Api "Create $Suffix project" POST '/api/projects' 201 @{ name = $name }
    $projectId = [int] $exchange.Response.Body.id
    # Register the resource before checking headers so cleanup also covers a malformed 201.
    $createdProjectIds.Add($projectId)
    Assert-Response $exchange 'Project ID captured' ($projectId -gt 0) 'A positive project ID is required.'
    Assert-Response $exchange 'Project name' ($exchange.Response.Body.name -ceq $name) 'The server must preserve the submitted name.'
    Assert-Response $exchange 'Location' ($exchange.Response.Headers['Location'] -match "/api/projects/$projectId`$") 'Location must identify the created project.'
    return $projectId
}

function New-LabTask {
    param([int] $ProjectId, [string] $Title)
    $exchange = Invoke-Api "Create task: $Title" POST '/api/tasks' 201 @{ projectId = $ProjectId; title = $Title }
    $taskId = [int] $exchange.Response.Body.id
    Assert-Response $exchange 'Task ID captured' ($taskId -gt 0) 'A positive task ID is required.'
    Assert-Response $exchange 'Task project' ($exchange.Response.Body.projectId -eq $ProjectId) "Expected project $ProjectId."
    Assert-Response $exchange 'Initial status' ($exchange.Response.Body.status -ceq 'Todo') 'A new task must be Todo.'
    Assert-Response $exchange 'Location' ($exchange.Response.Headers['Location'] -match "/api/tasks/$taskId`$") 'Location must identify the created task.'
    return $taskId
}

try {
    if ($Phase -in @('Part1', 'All')) {
        $list = Invoke-Api 'List projects' GET '/api/projects' 200
        Assert-Response $list 'JSON array' ($list.Response.Body -is [array]) 'The project list must be a JSON array.'
        $projectId = New-LabProject 'part1'
        $taskId = New-LabTask $projectId 'Write Dockerfile'
        $tasks = Invoke-Api 'List project tasks' GET "/api/tasks?projectId=$projectId" 200
        $projectTasks = @($tasks.Response.Body)
        Assert-Response $tasks 'Only own task' ($projectTasks.Count -eq 1 -and $projectTasks[0].id -eq $taskId) 'A fresh project must contain the one created task.'
        $changed = Invoke-Api 'Todo to InProgress' PATCH "/api/tasks/$taskId/status" 200 @{ status = 'InProgress' }
        Assert-Response $changed 'InProgress status' ($changed.Response.Body.status -ceq 'InProgress') 'The task must move to InProgress.'
        $project = Invoke-Api 'Get created project' GET "/api/projects/$projectId" 200
        Assert-Response $project 'Requested project' ($project.Response.Body.id -eq $projectId) 'The response must identify the requested project.'

        $empty = Invoke-Api 'Reject empty project name' POST '/api/projects' 400 @{ name = '' }
        Assert-Response $empty 'Validation errors' ($empty.Response.Body.errors.Count -gt 0) 'The response must contain field validation errors.'
        $duplicate = Invoke-Api 'Reject duplicate project name' POST '/api/projects' 409 @{ name = $project.Response.Body.name }
        Assert-Response $duplicate 'Conflict detail' (-not [string]::IsNullOrWhiteSpace($duplicate.Response.Body.detail)) 'The conflict must explain its cause in detail.'
        $conflictTaskId = New-LabTask $projectId 'Forbidden direct transition'
        $forbidden = Invoke-Api 'Reject Todo to Done' PATCH "/api/tasks/$conflictTaskId/status" 409 @{ status = 'Done' }
        Assert-Response $forbidden 'Transition detail' (-not [string]::IsNullOrWhiteSpace($forbidden.Response.Body.detail)) 'The response must explain the forbidden transition.'
        $null = Invoke-Api 'Missing task' GET "/api/tasks/$missingId" 404

        $updated = Invoke-Api 'Update task' PUT "/api/tasks/$taskId" 200 @{ title = 'Dockerfile prepared'; description = 'Lab 1 replay'; dueDate = [DateTime]::UtcNow.AddDays(7).ToString('yyyy-MM-dd') }
        Assert-Response $updated 'Updated title' ($updated.Response.Body.title -ceq 'Dockerfile prepared') 'The update must be visible in the response.'
        $done = Invoke-Api 'InProgress to Done' PATCH "/api/tasks/$taskId/status" 200 @{ status = 'Done' }
        Assert-Response $done 'Done status' ($done.Response.Body.status -ceq 'Done') 'The allowed transition must finish the task.'
    }

    if ($Phase -in @('Part2', 'All')) {
        $statsProjectId = New-LabProject 'stats'
        $null = New-LabTask $statsProjectId 'Todo without a due date'
        $inProgressId = New-LabTask $statsProjectId 'Task in progress'
        $null = Invoke-Api 'Prepare statistics InProgress task' PATCH "/api/tasks/$inProgressId/status" 200 @{ status = 'InProgress' }
        $overdueId = New-LabTask $statsProjectId 'Overdue Todo task'
        # Updating an existing task keeps the statistics fixture compatible with
        # the optional rule that rejects past dates only during task creation.
        $null = Invoke-Api 'Prepare overdue task' PUT "/api/tasks/$overdueId" 200 @{ title = 'Overdue Todo task'; description = 'UTC date minus two days'; dueDate = [DateTime]::UtcNow.AddDays(-2).ToString('yyyy-MM-dd') }
        $stats = Invoke-Api 'Project statistics' GET "/api/projects/$statsProjectId/stats" 200
        foreach ($field in ([ordered]@{ projectId = $statsProjectId; total = 3; todo = 2; inProgress = 1; done = 0; overdue = 1 }).GetEnumerator()) {
            Assert-Response $stats "Statistics: $($field.Key)" ($stats.Response.Body[$field.Key] -eq $field.Value) "Expected $($field.Value), received $($stats.Response.Body[$field.Key])."
        }
        $null = Invoke-Api 'Statistics of missing project' GET "/api/projects/$missingId/stats" 404
    }

    if ($IncludePastDueValidation) {
        $optionalProjectId = New-LabProject 'optional'
        $pastDue = Invoke-Api 'Reject creation with a past due date' POST '/api/tasks' 400 @{ projectId = $optionalProjectId; title = 'Past due date must be rejected'; dueDate = [DateTime]::UtcNow.AddDays(-2).ToString('yyyy-MM-dd') }
        Assert-Response $pastDue 'Validation body' ($pastDue.Response.Body -is [System.Collections.IDictionary]) 'The validation error must be a JSON object.'
    }
}
catch {
    $failure = $_.Exception.Message
}
finally {
    if (-not $KeepData) {
        foreach ($createdProjectId in $createdProjectIds) {
            try { $null = Invoke-Api "Clean up own project $createdProjectId" DELETE "/api/projects/$createdProjectId" 204 }
            catch { $cleanupFailures.Add($_.Exception.Message) }
        }
    }
    $summary = [ordered]@{
        schemaVersion = 1
        runId = $runId
        phase = $Phase
        baseUrl = $BaseUrl
        startedAtUtc = $startedAt.ToString('O')
        finishedAtUtc = [DateTimeOffset]::UtcNow.ToString('O')
        passed = ($null -eq $failure -and $cleanupFailures.Count -eq 0)
        failure = $failure
        optionalPastDueValidation = [bool] $IncludePastDueValidation
        keptData = [bool] $KeepData
        createdProjectIds = $createdProjectIds.ToArray()
        cleanupFailures = $cleanupFailures.ToArray()
        exchanges = $exchanges.ToArray()
    }
    $evidencePath = Join-Path $runDirectory 'http-evidence.json'
    $summary | ConvertTo-Json -Depth 40 | Set-Content -LiteralPath $evidencePath -Encoding utf8
    Write-Host "Evidence: $evidencePath"
}

if ($failure) { throw $failure }
if ($cleanupFailures.Count -gt 0) { throw ($cleanupFailures -join [Environment]::NewLine) }
Write-Host "PASS: $Phase; $($exchanges.Count) HTTP requests."
